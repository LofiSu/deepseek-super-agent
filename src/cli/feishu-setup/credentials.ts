import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import readline from 'node:readline'
import { stdin as input, stdout as output } from 'node:process'

export const DEFAULT_FEISHU_ENV_BASENAME = 'feishu.env'

export interface FeishuCredentialRecord {
  appId: string
  appSecret: string
  baseUrl: string
  chatId?: string
  botOpenId?: string
  actorAllowlist?: string
  dropSelf?: string
  p2pDirect?: boolean
}

export function defaultFeishuCredentialsPath(home: string): string {
  return path.join(home, DEFAULT_FEISHU_ENV_BASENAME)
}

export function ensurePrivateDir(dir: string): void {
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 })
  try {
    fs.chmodSync(dir, 0o700)
  } catch {
    /* best effort on platforms without chmod */
  }
}

export function writeFeishuEnvFile(filePath: string, record: FeishuCredentialRecord): void {
  ensurePrivateDir(path.dirname(filePath))
  const lines = [
    '# Generated by ds-agent feishu setup — do not commit.',
    `FEISHU_APP_ID=${record.appId}`,
    `FEISHU_APP_SECRET=${record.appSecret}`,
    `FEISHU_BASE_URL=${record.baseUrl}`,
  ]
  if (record.chatId) lines.push(`FEISHU_CHAT_ID=${record.chatId}`)
  if (record.botOpenId) lines.push(`FEISHU_BOT_OPEN_ID=${record.botOpenId}`)
  if (record.actorAllowlist) lines.push(`DS_AGENT_ACTOR_ALLOWLIST=${record.actorAllowlist}`)
  if (record.dropSelf) lines.push(`DS_AGENT_DROP_SELF=${record.dropSelf}`)
  if (record.p2pDirect) lines.push('DS_AGENT_FEISHU_P2P_DIRECT=1')
  lines.push('')
  const body = `${lines.join('\n')}`
  fs.writeFileSync(filePath, body, { encoding: 'utf8', mode: 0o600 })
  try {
    fs.chmodSync(filePath, 0o600)
  } catch {
    /* best effort */
  }
}

export function parseFeishuEnvFile(text: string): Partial<FeishuCredentialRecord> {
  const out: Partial<FeishuCredentialRecord> = { baseUrl: 'https://open.feishu.cn' }
  for (const rawLine of text.split(/\r?\n/u)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue
    const eq = line.indexOf('=')
    if (eq <= 0) continue
    const key = line.slice(0, eq).trim()
    const value = line.slice(eq + 1).trim()
    if (key === 'FEISHU_APP_ID') out.appId = value
    else if (key === 'FEISHU_APP_SECRET') out.appSecret = value
    else if (key === 'FEISHU_BASE_URL') out.baseUrl = value
    else if (key === 'FEISHU_CHAT_ID') out.chatId = value
    else if (key === 'FEISHU_BOT_OPEN_ID') out.botOpenId = value
    else if (key === 'DS_AGENT_ACTOR_ALLOWLIST') out.actorAllowlist = value
    else if (key === 'DS_AGENT_DROP_SELF') out.dropSelf = value
    else if (key === 'DS_AGENT_FEISHU_P2P_DIRECT' && value === '1') out.p2pDirect = true
  }
  return out
}

export function readFeishuEnvFileIfPresent(filePath: string): Partial<FeishuCredentialRecord> | undefined {
  if (!fs.existsSync(filePath)) return undefined
  return parseFeishuEnvFile(fs.readFileSync(filePath, 'utf8'))
}

/** Hidden TTY line input (getpass-style). Falls back to visible prompt when not a TTY. */
export function promptLine(question: string, hidden = false): Promise<string> {
  if (!hidden || !input.isTTY) {
    const rl = readline.createInterface({ input, output })
    return new Promise(resolve => {
      rl.question(question, answer => {
        rl.close()
        resolve(answer.trim())
      })
    })
  }
  return new Promise(resolve => {
    const stdin = input
    const wasRaw = stdin.isRaw
    output.write(question)
    stdin.setRawMode(true)
    stdin.resume()
    stdin.setEncoding('utf8')
    let value = ''
    const onData = (chunk: string): void => {
      for (const char of chunk) {
        if (char === '\n' || char === '\r' || char === '\u0004') {
          stdin.setRawMode(wasRaw ?? false)
          stdin.pause()
          stdin.removeListener('data', onData)
          output.write('\n')
          resolve(value.trim())
          return
        }
        if (char === '\u0003') {
          stdin.setRawMode(wasRaw ?? false)
          stdin.pause()
          stdin.removeListener('data', onData)
          process.exit(130)
        }
        if (char === '\u007f' || char === '\b') {
          value = value.slice(0, -1)
          continue
        }
        value += char
      }
    }
    stdin.on('data', onData)
  })
}

export function randomToken(bytes = 16): string {
  return crypto.randomBytes(bytes).toString('hex')
}
